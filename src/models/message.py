from __future__ import annotations

from enum import StrEnum
from typing import TYPE_CHECKING
import uuid

from sqlalchemy import Enum, ForeignKey, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .base import Base, TimestampMixin

if TYPE_CHECKING:
    from .chat import Chat
    from .file import Attachment
    from .user import User


class MessageRole(StrEnum):
    """Exact roles expected by the ReqLens frontend.

    - client    : message sent by the client user
    - developer : message sent by the developer user
    - ai        : message generated by the AI analysis service
    - system    : informational message produced by a slash command
    """

    CLIENT = "client"
    DEVELOPER = "developer"
    AI = "ai"
    SYSTEM = "system"


class Message(Base, TimestampMixin):
    """A single message within a chat room."""

    __tablename__ = "messages"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
    )
    chat_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("chats.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    # Null for AI-generated and system messages.
    author_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    role: Mapped[MessageRole] = mapped_column(
        Enum(MessageRole, name="message_role"),
        nullable=False,
    )
    content: Mapped[str] = mapped_column(Text, nullable=False)

    # Relations
    chat: Mapped[Chat] = relationship(
        "Chat",
        back_populates="messages",
    )
    author: Mapped[User | None] = relationship(
        "User",
        back_populates="messages",
    )
    attachments: Mapped[list[Attachment]] = relationship(
        "Attachment",
        back_populates="message",
    )
